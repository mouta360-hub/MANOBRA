const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/www/roguelike_adventure.js', 'utf8');
const context = { window: { addEventListener: () => {} }, document: { getElementById: () => null }, console, Math, Date, setTimeout, SPECIAL_PIECES_CATALOG: { a: { name: 'A' }, b: { name: 'B' }, c: { name: 'C' }, d: { name: 'D' } } };
vm.createContext(context);
vm.runInContext(source, context);
const run = context.window.RoguelikeRun;
assert.equal(context.rogueAtShop(), false);
context.openRoguelikeShop();
assert.equal(Object.keys(run.shopOffers).length, 0);
run.active = true;
const node = { id: 'shop-1', type: 'shop', row: 1, col: 0, cleared: true };
run.map = [[{type:'battle'}], [node]];
run.pendingNode = node; run.mapRow = 1; run.mapCol = 0;
assert.equal(context.rogueAtShop(), false, 'unvisited shop must be locked');
run.visited = ['shop-1'];
assert.equal(context.rogueAtShop(), true);
assert.equal(context.rogueShopSelection(context.rogueShopId()).length, 3);
run.gold = 100;
const offered = context.rogueShopSelection(context.rogueShopId())[0];
context.buyRoguelikePiece(offered, 35);
assert.equal(run.roster.includes(offered), true);
run.pendingNode = null;
const count = run.roster.length;
context.buyRoguelikePiece('b', 35);
assert.equal(run.roster.length, count, 'cannot purchase outside shop');
console.log('Shop access: 6 checks passed');
