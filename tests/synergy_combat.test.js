const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const E=require('../www/engine.js');
const run={active:true,deployed:{'10':'assassino_sombras','11':'predador'},enemyDeployed:{'23':'escudeiro'},abilityState:{}};
const window={ManobraEngine:E,RoguelikeRun:run,__manobraApp:{humanSide:E.WHITE},addEventListener(){}};
const ctx={window,document:{querySelectorAll(){return []}},setInterval(){}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('www/special_pieces.js','utf8'),ctx);
vm.runInContext(fs.readFileSync('www/roguelike_runtime.js','utf8'),ctx);
const rt=window.RoguelikeRuntime;
const board=Array(E.N).fill(0);board[10]=2;board[11]=2;board[23]=3;
const mv={t:'k',from:10,to:23};const game={over:false,st:{b:board,turn:E.WHITE},legal(){return {moves:[mv]}}};
assert.equal(rt.synergyFor(board,E.WHITE,10,'pierce').tier,2);
assert.equal(rt.beforeMove(game,mv),true,'dupla rompe escudo do inimigo');
assert.equal(run.abilityState.charges['0:10:assassino_sombras'],1,'gasta carga do atacante');
run.abilityState={};delete run.deployed['11'];board[11]=0;
assert.equal(rt.synergyFor(board,E.WHITE,10,'pierce'),null);
assert.equal(rt.beforeMove(game,mv),false,'sem parceiro, escudo protege');
run.abilityState={};run.deployed['11']='predador';board[11]=2;run.deployed['12']='duelista';board[12]=2;
assert.equal(rt.synergyFor(board,E.WHITE,10,'pierce').tier,3,'trio ativo');
run.enemyDeployed={'24':'oraculo'};board[24]=3;run.deployed={};board[10]=0;board[11]=0;board[12]=0;
assert.equal(rt.synergyFor(board,E.BLACK,24,'guard'),null);
run.enemyDeployed['25']='sentinela';board[25]=3;
assert.equal(rt.synergyFor(board,E.BLACK,24,'guard').tier,2);
run.enemyDeployed['37']='lancer';board[37]=3;
assert.equal(rt.synergyFor(board,E.BLACK,24,'guard').tier,3);
console.log('ok - sinergias: dupla, trio, ausência de parceiro e consumo de carga');
// A Falange protege um aliado comum (fora do trio) na mesma coluna.
run.abilityState={};
run.deployed={'10':'lancer','12':'sentinela'};
run.enemyDeployed={};
const b2=Array(E.N).fill(0);
b2[10]=2;b2[12]=2;b2[23]=2;b2[36]=3;
const mv2={t:'k',from:36,to:23};
const g2={over:false,st:{b:b2,turn:E.BLACK},legal(){return {moves:[mv2]}}};
assert.equal(rt.beforeMove(g2,mv2),false,'Falange protege aliado comum na mesma coluna');
assert.equal(run.abilityState.charges['0:10:lancer'],1,'Falange consome carga do protetor');
