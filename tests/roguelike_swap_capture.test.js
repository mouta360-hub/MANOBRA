const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const E=require('../www/engine.js');
const run={active:true,gold:0,deployed:{'10':'ilusionista'},enemyDeployed:{'24':'sentinela'},abilityState:{charges:{'0:10:ilusionista':1,'1:24:sentinela':1},abilityCooldown:{'0:10:ilusionista':2,'1:24:sentinela':3}}};
const window={ManobraEngine:E,RoguelikeRun:run,__manobraApp:{humanSide:E.WHITE},addEventListener(){}};
const ctx={window,document:{querySelectorAll(){return []}},setInterval(){}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('www/special_pieces.js','utf8'),ctx);
vm.runInContext(fs.readFileSync('www/roguelike_runtime.js','utf8'),ctx);
const rt=window.RoguelikeRuntime;
const board=Array(E.N).fill(0);board[10]=1;board[24]=3;
const move={t:'s',from:10,to:24};
const game={over:false,st:{b:board,turn:E.WHITE},legal(){return {moves:[move]}}};
assert.equal(rt.beforeMove(game,move),true);
board[10]=3;board[24]=1;game.st.turn=E.BLACK;
rt.afterMove(game,move,false);
assert.equal(run.deployed['24'],'ilusionista');
assert.equal(run.enemyDeployed['10'],'sentinela');
assert.equal(run.abilityState.charges['0:24:ilusionista'],1);
assert.equal(run.abilityState.charges['1:10:sentinela'],1);
assert.equal(run.abilityState.abilityCooldown['0:24:ilusionista'],1);
assert.equal(run.abilityState.abilityCooldown['1:10:sentinela'],3);
assert.equal(run.deployed['10'],undefined);
assert.equal(run.enemyDeployed['24'],undefined);
// Remoção compulsória de sétima defesa deve limpar a habilidade da vítima.
run.enemyDeployed={'24':'escudeiro'};
run.abilityState.charges['1:24:escudeiro']=1;
const b2=Array(E.N).fill(0);b2[24]=3;
const x={t:'x',from:-1,to:24};
const g2={over:false,st:{b:b2,turn:E.WHITE},legal(){return {moves:[x]}}};
assert.equal(rt.beforeMove(g2,x),true);
b2[24]=0;
rt.afterMove(g2,x,false);
assert.equal(run.enemyDeployed['24'],undefined);
assert.equal(run.abilityState.charges['1:24:escudeiro'],undefined);
console.log('ok - troca mantém identidade e recarga; remoção compulsória limpa peça');
